- スケジュール（/schedule）：営業の予定表。日・週・月・リストの表示、メンバーを選んで表示。
- アポ一覧（/appointments）：アポの一覧。タブ「前日確認」（/appointments/day-before）「変更依頼」（/appointments/change-requests）。右上に「既存リストのアポを登録」。

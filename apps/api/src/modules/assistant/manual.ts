- 宛先（TO、複数はカンマ区切り。初期値は管理の「通知の宛先」）、件名（送ると最後に【担当：姓】が付く）、本文（送ると最後に送信者の行が入る）。内容を確かめて直せる。
- 「送信」：送る。各メールは1回だけ送られ、送ったあとは「内容を直して【再送】する」で件名に【再送】を付けて送り直す。
- 「いまのアポの内容で作り直す」：アポの内容を変えたあと、本文をいまの内容で作り直す。
- 「あとで送る」：送らずにアポのページへ戻る。アポのページに「営業さんへのメール（N1）はまだ送っていません。」と出るので、「確認して送る」からいつでも送れる。直しかけの内容は保存されない（開き直すとアポの内容から作られる）。
